def write_strip(path: Path, glyphs: dict, gw: int, gh: int) -> None:
    cell_w = gw + 1
    width = 1 + len(ORDER) * cell_w
    img = Image.new("RGBA", (width, gh), CLR)
    px = img.load()
    for y in range(gh):
        px[0, y] = SEP
    x = 1
    for ch in ORDER:
        rows = glyphs[ch]
        assert len(rows) == gh, (ch, len(rows), gh)
        for gy in range(gh):
            bits = rows[gy]
            for gx in range(gw):
                on = (bits >> (gw - 1 - gx)) & 1
                px[x + gx, gy] = INK if on else CLR
        x += gw
        for y in range(gh):
            px[x, y] = SEP
        x += 1
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path)
    print(f"wrote {path} ({img.size[0]}x{img.size[1]}, {len(ORDER)} glyphs)")


